"""Four sensitivity tables: the number of controls (three tracks), the redraw of the target test split, its directions and the time-ordered configuration.
Input: results/analysis/extra_controls_verdict/ctrl40_verdict.csv, size_matched_verdict/size_matched_verdict.csv (also its lots_* columns), redrawn_verdict/{resplit_verdict,resplit_jaccard}.csv
Output: tables/tab_ctrl50.tex, tables/tab_resplit.tex, tables/tab_resplit_rq1.tex, tables/tab_forward.tex. The numbers of the text are printed to the standard output.
"""
import sys
from pathlib import Path

import pandas as pd

from defectshift import config  # noqa: E402

HERE = Path(__file__).resolve().parents[1]
R = Path(config.RESULTS_DIR) / "analysis"
ORDER = ["cat_005", "cat_019", "cat_039", "cat_045", "cat_050", "x_time", "y_time"]
SIZE_MATCHED = "size_matched_verdict/size_matched_verdict.csv"


def tex(s):
    return s.replace("_", r"\_")


def f(x):
    return f"{x:+.1f}"


def lots(r):
    return f"{r.lots_ctrl_min} / {r.lots_ctrl_median:g} / {r.lots_ctrl_max} ({r.lots_domain_disjoint})"


def tab_ctrl50():
    v = pd.read_csv(R / "extra_controls_verdict/ctrl40_verdict.csv")
    t = {k: g.set_index("dom").loc[ORDER] for k, g in v.groupby("track")}
    for k in ("T2", "T3"):  # the same 8 models, so the gaps must be equal
        assert (t[k].gap_rmse - t["T0"].gap_rmse).abs().max() < 1e-9
    sm = pd.read_csv(R / SIZE_MATCHED).set_index("dom").loc[ORDER]   # size-matched controls (size_matched_verdict.py)
    assert (sm.gap_rmse - t["T2"].gap_rmse).abs().max() < 1e-9      # the same eight-model domain values as track T2
    rows = []
    for d in ORDER:
        a, b = t["T0"].loc[d], t["T2"].loc[d]
        rows.append(f"{tex(d)} & {f(a.gap_rmse)} / {f(a.gap_mae)} & {a.k_rmse} / {a.k_mae} & {b.k_rmse} / {b.k_mae} & {sm.loc[d].n_ctrl} & {sm.loc[d].k_rmse} / {sm.loc[d].k_mae} & {lots(sm.loc[d])} \\\\")
    m0, m2 = t["T0"].iloc[0], t["T2"].iloc[0]
    rows.append(r"\midrule")
    rows.append(f"Control maximum & & {f(m0.ctrl_max_rmse)} / {f(m0.ctrl_max_mae)} & {f(m2.ctrl_max_rmse)} / {f(m2.ctrl_max_mae)} & & & \\\\")
    (HERE / "tables/tab_ctrl50.tex").write_text(r"""% generated by tools/tables_sensitivity.py
\begin{table*}[!t]
\footnotesize
\centering
\caption{Sensitivity of the RQ2 verdict to the controls (lot-disjoint target test rows; RMSE / MAE). Gap: domain-level target-reference gap (\%) over the eight models. $k$: number of controls with a strictly smaller gap, out of the ten original controls and all 50 controls; $k = N$ means that the domain exceeds all $N$ controls. Of the 40 added controls, 20 have the size of the \texttt{cat\_050} domain. The two tracks use the same eight models and are not pooled; the gaps differ from Table~\ref{tab:rq2} because of the model set. Size-matched: the controls among the 50 whose training size $n^\ast$ and number of target test rows are each within 10\% of those of the domain; their number $N$ differs by domain, and $k$ is counted among them. The number of target test lots is descriptive and is not part of the size rule: for the size-matched controls it is given as minimum / median / maximum over the eligible controls, with the value of the challenge domain (lot-disjoint evaluation rows) in parentheses; the size rule compares the target test rows of a control with all rows of $B_{\mathrm{te}}$ of the domain.}
\label{tab:ctrl50}
\begin{tabular}{lcccccc}
\toprule
Domain & Gap (eight models) & $k$ / 10, original & $k$ / 50, all & $N$, size-matched & $k$, size-matched & Test lots, size-matched \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}
""")
    print(pd.concat({k: t[k][["gap_rmse", "k_rmse", "gap_mae", "k_mae", "ctrl_max_rmse", "ctrl_max_mae"]] for k in t}, axis=1).round(2).to_string())


def tab_resplit():
    v = pd.read_csv(R / "redrawn_verdict/resplit_verdict.csv")
    v = v[v.variant == "not_shared"]
    assert v.n_ctrl.eq(50).all() and v.groupby("dom").size().eq(6).all()
    head = ["Canonical"] + [f"Redraw {k}" for k in range(1, 6)]
    rows = []
    for d in ORDER:
        g = v[v.dom == d].set_index("k").sort_index()
        cells = []
        for k, r in g.iterrows():
            a = f(r.gap_rmse) + ("*" if r.k_rmse == 50 else "")
            b = f(r.gap_mae) + ("*" if r.k_mae == 50 else "")
            cells.append(f"{a} / {b}")
        rows.append(tex(d) + " & " + " & ".join(cells) + " \\\\")
    r0 = v.iloc[0]
    rows.append(r"\midrule")
    rows.append("Control maximum & \\multicolumn{6}{c}{" + f"{f(r0.ctrl_max_rmse)} / {f(r0.ctrl_max_mae)} (the same 50 controls for every partition)" + "} \\\\")
    j = pd.read_csv(R / "redrawn_verdict/resplit_jaccard.csv")
    jm = j.groupby("dom").jaccard.median()
    (HERE / "tables/tab_resplit.tex").write_text(r"""% generated by tools/tables_sensitivity.py
\begin{table*}[!t]
\footnotesize
\centering
\setlength{\tabcolsep}{4pt}
\caption{Target-reference gaps (\%, RMSE / MAE) of the eight models on the lot-disjoint target test rows of the canonical target partition and five redrawn partitions ($B_{\mathrm{scr}}$ fixed, source-selected hyperparameters reused). *: the gap exceeds all 50 fixed controls for that measure. The partitions share source-side tuning and controls, and their test lot sets overlap (median pairwise Jaccard index """ + f"{jm.min():.2f} to {jm.max():.2f}" + r""" by domain); they are a sensitivity analysis, not independent replicates. The redrawn partitions use about 28\% of $B$ for testing and 45\% for training (canonical: 25\% and 48\%).}
\label{tab:resplit}
\begin{tabular}{l""" + "c" * 6 + r"""}
\toprule
Domain & """ + " & ".join(head) + r""" \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}
""")
    s = v.groupby("dom").agg(r50=("k_rmse", lambda x: (x == 50).sum()), m50=("k_mae", lambda x: (x == 50).sum()),
                            b50=("k_both", lambda x: (x == 50).sum()), rmin=("gap_rmse", "min"), rmax=("gap_rmse", "max"),
                            mmin=("gap_mae", "min"), mmax=("gap_mae", "max"), kr_min=("k_rmse", "min"), kr_max=("k_rmse", "max"))
    print(s.loc[ORDER].round(1).to_string())
    print("jaccard median by domain", jm.round(2).to_dict())
    w = pd.read_csv(R / "redrawn_verdict/resplit_verdict.csv")
    w = w[w.variant == "rest99"].groupby("dom").agg(b50=("k_both", lambda x: (x == 50).sum()), m50=("k_mae", lambda x: (x == 50).sum()), r50=("k_rmse", lambda x: (x == 50).sum()))
    print("rest99", w.loc[ORDER].to_string())


def tab_resplit_rq1():
    """Sensitivity of the direction comparison to the redraw (8 models, canonical + 5 redraws). Input redrawn_directions/rq1_resplit_domain.csv."""
    d = pd.read_csv(R / "redrawn_directions/rq1_resplit_domain.csv")
    assert d.groupby(["dom", "metric"]).size().eq(6).all()
    rows = []
    for dom in ORDER:
        cells = []
        for met in ("rmse", "mae"):
            g = d[(d.dom == dom) & (d.metric == met)]
            opp = int((g.dir_io == "opposite").sum())
            same = int((g.dir_sn == "same").sum())
            follow = int(((g.io * g.s_pct) > 0).sum())
            cells.append(f"{opp} & {same} & {follow} & {f(g.tr.min())} to {f(g.tr.max())}")
        rows.append(tex(dom) + " & " + " & ".join(cells) + " \\\\")
    (HERE / "tables/tab_resplit_rq1.tex").write_text(r"""% generated by tools/tables_sensitivity.py
\begin{table*}[!t]
\footnotesize
\centering
\setlength{\tabcolsep}{3.5pt}
\caption{RQ1 directions across the canonical target partition and five redrawn partitions (eight models, lot-disjoint target test rows; counts out of six partitions). Opp.: the ID--OOD gap and the target-reference gap have opposite signs. Norm.: the scale-normalized contrast and the target-reference gap have the same sign. $s$: the ID--OOD gap has the same sign as $s - 1$. Range: target-reference gap (\%) over the six partitions.}
\label{tab:resplit-rq1}
\begin{tabular}{lcccccccc}
\toprule
 & \multicolumn{4}{c}{RMSE} & \multicolumn{4}{c}{MAE} \\
\cmidrule(lr){2-5}\cmidrule(lr){6-9}
Domain & Opp. & Norm. & $s$ & Range & Opp. & Norm. & $s$ & Range \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}
""")
    for met in ("rmse", "mae"):
        g = d[d.metric == met]
        print(met, "ID-OOD = s:", int(((g.io * g.s_pct) > 0).sum()), "/", len(g), " opposite:", int((g.dir_io == "opposite").sum()))


def tab_forward():
    """Main table of the time-ordered comparison (reference that uses only earlier lots). Input analysis/time_ordered_verdict/{forward_verdict,forward_split}.csv."""
    v = pd.read_csv(R / "time_ordered_verdict/forward_verdict.csv")
    s = pd.read_csv(R / "time_ordered_verdict/forward_split.csv")
    s = s[s["mode"] == "time_ordered"].set_index("axis")
    canon_n = {"x_time": 3420, "y_time": 3417}   # n* of the dataset table
    rows = []
    for ax in ("x_time", "y_time"):
        for var, lab in (("not_shared", "lot-disjoint rows"), ("rest99", "top 1\\% excluded")):
            r = v[(v.axis == ax) & (v.variant == var)].iloc[0]
            assert r.n_ctrl == 10 and r.k_rmse <= 10 and r.k_mae <= 10
            nn = f"{canon_n[ax]:,} $\\to$ {int(s.loc[ax, 'n_star_fo']):,}" if var == "not_shared" else ""
            first = tex(ax) if var == "not_shared" else ""
            rows.append(f"{first} & {lab} & {f(r.r0_rmse)} / {f(r.r0_mae)} & {f(r.r1_rmse)} / {f(r.r1_mae)} & "
                        f"{f(r.r2_rmse)} / {f(r.r2_mae)} & {f(r.ctrl_max_rmse)} / {f(r.ctrl_max_mae)} & {int(r.k_rmse)} / {int(r.k_mae)} & {nn} \\\\")
        if ax == "x_time":
            rows.append(r"\midrule")
    (HERE / "tables/tab_forward.tex").write_text(r"""% generated by tools/tables_sensitivity.py
\begin{table*}[!t]
\footnotesize
\centering
\setlength{\tabcolsep}{4pt}
\caption{Target-reference gaps (\%, RMSE / MAE) of the temporal domains when the reference is fitted on earlier lots only (eight models, source-selected hyperparameters reused). Canonical: random lot-level target partition, reference fitted on lots on both sides of the test lots. Smaller $n^\ast$: canonical partition with the training size reduced to that of the time-ordered configuration. Earlier lots only: time-ordered target partition (the last 25\% of lots as test lots); source model and reference fitted only on lots that precede the first test record. Control maximum and $k$: the ten randomized lot-split controls given the same time-ordered split and rule (not pooled with the controls of Table~\ref{tab:rq2}); $k$ is the number of these controls with a smaller gap. The test rows of the time-ordered configuration differ from those of the other two columns, so a difference is not attributed to the restriction alone. $n^\ast$: canonical $\to$ earlier lots only.}
\label{tab:forward}
\begin{tabular}{llcccccc}
\toprule
Domain & Evaluated rows & Canonical & Smaller $n^\ast$ & Earlier lots only & Control maximum & $k$ / 10 & $n^\ast$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table*}
""")
    print(v[["axis", "variant", "r0_rmse", "r1_rmse", "r2_rmse", "ctrl_max_rmse", "k_rmse", "k_mae"]].round(1).to_string())


if __name__ == "__main__":
    if len(sys.argv) > 1:   # the generator takes no arguments and rewrites all of its outputs
        raise SystemExit(__doc__)
    tab_ctrl50()
    tab_resplit()
    tab_resplit_rq1()
    tab_forward()
