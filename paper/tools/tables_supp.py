"""Supplementary table: lot-disjoint target test accuracy per model x domain x training regime (output of lot_disjoint_accuracy.py).
Output: tables/tab_full_disjoint.tex"""
import sys
from pathlib import Path

import pandas as pd

from defectshift import config  # noqa: E402

R = Path(config.RESULTS_DIR) / "analysis/lot_disjoint_accuracy/full_disjoint_cells.csv"
HERE = Path(__file__).resolve().parent.parent
ORDER = ["cat_005", "cat_019", "cat_039", "cat_045", "cat_050", "x_time", "y_time"]
FAM = [("Classical", ["LinearRegression", "Ridge", "kNN", "SVR"]),
       ("Tree", ["DecisionTree", "RandomForest", "GBR", "XGBoost", "LightGBM", "CatBoost"]),
       ("Deep learning", ["MLP", "RealMLP", "TabM", "FT-Transformer", "NODE", "TabNet"]),
       ("Foundation", ["TabPFN", "TabICL", "TabFM", "TabDPT", "Kumo", "EXAONE"])]
NAME = {"LinearRegression": "Linear regression", "kNN": "$k$NN", "DecisionTree": "Decision tree", "RandomForest": "Random forest",
        "GBR": "Gradient boosting", "Kumo": "Kumo Tabular", "EXAONE": "EXAONE-Tabular"}
REG = ["ID_full", "ID_match", "OOD_match", "OOD_match_tuned"]


def main():
    c = pd.read_csv(R)
    c["dom"] = c.candidate.str.split("<=").str[0]
    out = []
    for j, k in enumerate(ORDER):
        d = c[c.dom == k].set_index(["model", "regime"])
        n = int(d.n_rows.iloc[0])
        rows = []
        for fam, ms in FAM:
            rows.append(rf"\multicolumn{{13}}{{l}}{{\textit{{{fam}}}}} \\")
            for m in ms:
                cells = []
                for r in REG:
                    if (m, r) in d.index:
                        x = d.loc[(m, r)]
                        cells += [f"{100 * x.rmse:.2f}", f"{100 * x.mae:.2f}", f"{x.r2:.2f}"]
                    else:
                        cells += ["--"] * 3
                rows.append(f"{NAME.get(m, m)} & " + " & ".join(cells) + r" \\")
        out.append(r"""\begin{table*}[!htbp]
\footnotesize
\setlength{\tabcolsep}{3pt}
\caption{Results on the lot-disjoint target test rows of domain """ + k.replace("_", r"\_") + f" ({n:,} rows)" + r""": mean over the five repetitions of RMSE and MAE ($\times 10^{-2}$) and $R^2$, for each training regime. OOD-match tuned exists only for the tuned models.""" + rf"\label{{tab:fullld-{j}}}" + r"""}
\begin{tabularx}{\textwidth}{Lcccccccccccc}
\toprule
 & \multicolumn{3}{c}{\textbf{ID-full}} & \multicolumn{3}{c}{\textbf{ID-match}} & \multicolumn{3}{c}{\textbf{OOD-match}} & \multicolumn{3}{c}{\textbf{OOD-match tuned}} \\
\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}\cmidrule(lr){11-13}
\textbf{Model} & RMSE & MAE & $R^2$ & RMSE & MAE & $R^2$ & RMSE & MAE & $R^2$ & RMSE & MAE & $R^2$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabularx}
\end{table*}
""")
    (HERE / "tables/tab_full_disjoint.tex").write_text("% generated by tools/tables_supp.py\n" + "\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) > 1:   # the generator takes no arguments and rewrites all of its outputs
        raise SystemExit(__doc__)
    main()
