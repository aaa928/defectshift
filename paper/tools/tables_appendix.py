def tab_forward_split():
    """Row accounting of the time-ordered split. Input analysis/time_ordered_verdict/forward_split.csv. Challenge domains: the time_ordered row; controls: the range of the controls rows."""
    s = pd.read_csv(R / "analysis/time_ordered_verdict/forward_split.csv")
    canon_n = {"x_time": 3420, "y_time": 3417}

    def rng(x, fmt="{:,}"):
        lo, hi = int(x.min()), int(x.max())
        return fmt.format(lo) if lo == hi else fmt.format(lo) + "--" + fmt.format(hi)

    cols = []
    for ax in ("x_time", "y_time"):
        r = s[(s["mode"] == "time_ordered") & (s.axis == ax)].iloc[0]
        c = s[(s["mode"] == "controls") & (s.axis == ax)]
        assert len(c) == 10
        cols.append((r, c))
    items = [
        ("Lots in the training candidates ($A_{\\mathrm{dev}}$ and $B_{\\mathrm{tr}}$)", lambda r: f"{int(r.lots_pool):,}", lambda c: rng(c.lots_pool)),
        ("Lots failing the rule (rows measured at or after the first test record)", lambda r: f"{int(r.violating_lots)} ({int(r.violating_rows):,})", lambda c: rng(c.violating_lots)),
        ("Rows removed with these lots, source / target", lambda r: f"{int(r.rows_removed_A):,} / {int(r.rows_removed_B):,}",
         lambda c: f"{rng(c.rows_removed_A)} / {rng(c.rows_removed_B)}"),
        ("Buffer lot (rows)", lambda r: f"1 ({int(r.buffer_rows)})", lambda c: f"1 ({rng(c.buffer_rows)})"),
        ("Target training rows, before $\\to$ after (controls: after)", lambda r: f"{int(r.n_B_tr_before):,} $\\to$ {int(r.n_B_tr):,}", lambda c: rng(c.n_B_tr)),
        ("$n^\\ast$, canonical $\\to$ earlier lots only", None, lambda c: rng(c.n_star_fo)),
        ("Test lots (rows)", lambda r: f"{int(r.te_lots)} ({int(r.n_B_te):,})", lambda c: f"{rng(c.te_lots)} ({rng(c.n_B_te)})"),
        ("Hours from the last training lot to the first test record", lambda r: f"{r.gap_hours:.1f}", lambda c: f"{c.gap_hours.min():.1f}--{c.gap_hours.max():.1f}"),
    ]
    lines = []
    for name, fr, fc in items:
        cells = []
        for ax, (r, c) in zip(("x_time", "y_time"), cols):
            cells.append(f"{canon_n[ax]:,} $\\to$ {int(r.n_star_fo):,}" if fr is None else fr(r))
        ctrl = [fc(c) for (r, c) in cols]
        lines.append(f"{name} & {cells[0]} & {cells[1]} & {ctrl[0]} & {ctrl[1]} \\\\")
    (HERE / "tables/tab_forward_split.tex").write_text(r"""% generated by tools/tables_appendix.py
\begin{table*}[!t]
\footnotesize
\centering
\setlength{\tabcolsep}{6pt}
\caption{Row accounting of the time-ordered configuration (Section~\ref{sec:results:sensitivity}). Challenge: the domain; controls: range over the ten time-ordered controls. Source-side rows are removed in the controls only, whose source pool is the whole period; in the challenge domains the source pool lies before the cutoff. The rule excludes whole lots, so rows of a failing lot are removed even when only some of them are measured late. Row counts refer to the training candidates $A_{\mathrm{dev}}$ and $B_{\mathrm{tr}}$ unless stated otherwise.}
\label{tab:forward-split}
\begin{tabular}{p{6.2cm}cccc}
\toprule
 & \multicolumn{2}{c}{Challenge} & \multicolumn{2}{c}{Controls} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}
 & x\_time & y\_time & x\_time & y\_time \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table*}
""")



