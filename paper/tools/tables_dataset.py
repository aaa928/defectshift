"""Two tables of the dataset section: domain summary (tab_domains.tex) and shift diagnostic summary (tab_shift.tex).
Input (results/ and cache/): screening/runs/screening_main/selection/final_domains.json, benchmark/runs/benchmark_canonical/rows.csv (main run of 22 models: sizes, n*),
cache/dry_run/redrawn_split_1.json (output of scripts/extra/run_redrawn_target_splits.py --resplit 1 --dry-run: number of canonical test lots, share of shared lots), analysis/lot_disjoint/disjoint_domain.csv (spread ratio s),
shift_diag/main/summary/candidates.csv (feature-OT excess, DISDE, AUC), shift_statistics/main/shift_stats.csv (difference of the mean outcome)."""
import json
import sys
from pathlib import Path

import pandas as pd

from defectshift import config  # noqa: E402

R = Path(config.RESULTS_DIR)
C = Path(config.CACHE_DIR)
OUT = Path(__file__).resolve().parent.parent / "tables"
ORDER = ["cat_005", "cat_019", "cat_039", "cat_045", "cat_050", "x_time", "y_time"]
KIND = dict(cat_005="process condition", cat_019="process condition", cat_039="process condition", cat_045="process condition",
            cat_050="process condition", x_time="temporal (input time)", y_time="temporal (outcome time)")


def short(c):
    return c.split("<=")[0]


def tex(s):
    return s.replace("_", r"\_")


def main():
    fin = json.load(open(R / "screening/runs/screening_main/selection/final_domains.json"))
    names = fin["categorical"] + fin["temporal"]
    rows = pd.read_csv(R / "benchmark/runs/benchmark_canonical/rows.csv")
    rows = rows[rows.candidate.isin(names) & (rows.status == "ok")]
    g = rows.groupby("candidate").agg(n_A=("n_A", "first"), n_B=("n_B", "first"), ns_lo=("n_star", "min"), ns_hi=("n_star", "max"),
                                      n_id=("n_id", "first"), n_ood=("n_ood", "first"))
    assert (rows.groupby("candidate").n_A.nunique() == 1).all() and (rows.groupby("candidate").n_ood.nunique() == 1).all()
    dry = json.load(open(C / "dry_run/redrawn_split_1.json"))["domains"]
    dd = pd.read_csv(R / "analysis/lot_disjoint/disjoint_domain.csv")
    dd = dd[dd.variant == "disjoint"].pivot(index="candidate", columns="metric", values="s")
    lines = []
    for n in sorted(names, key=lambda c: ORDER.index(short(c))):
        k = short(n)
        r, d = g.loc[n], dry[n]["canonical"]
        assert d["B_te"] == r.n_ood, (n, d["B_te"], r.n_ood)
        ns = f"{r.ns_lo:,}" if r.ns_lo == r.ns_hi else f"{r.ns_lo:,}--{r.ns_hi:,}"
        lines.append(f"{tex(k)} & {KIND[k]} & {r.n_A:,} & {r.n_B:,} & {ns} & {r.n_id:,} & {r.n_ood:,} & {d['te_lots']} & "
                     f"{100 * d['te_shared_rows']:.1f} & {dd.loc[n, 'rmse']:.2f} & {dd.loc[n, 'mae']:.2f} \\\\")
    body = "\n".join(lines)
    (OUT / "tab_domains.tex").write_text(r"""% generated by tools/tables_dataset.py
\begin{table*}[!t]
\footnotesize
\centering
\caption{The seven challenge domains. $|A|$, $|B|$: source and target records. $n^\ast$: nominal training-pool size matched between the source model and the target-trained reference (range over the five repetitions); for models with early stopping, the actual numbers of training rows can differ between the two. $A_{\mathrm{held}}$, $B_{\mathrm{te}}$: source and target test records; lots: production lots in $B_{\mathrm{te}}$. Shared: share of $B_{\mathrm{te}}$ records whose lot also occurs in the source training pool $A_{\mathrm{dev}}$. $s$: outcome-scale ratio of the target test set (lot-disjoint rows) to the source test set, the ratio of standard deviations for RMSE and of mean absolute deviations from the median for MAE. The two temporal domains are defined by the median cutoff of their respective timestamp axes; within each domain, the target-side partitions are formed by random lot-level allocation, so the reference's training sample can include lots later than some test lots (Section~\ref{sec:protocol:reference}).}
\label{tab:domains}
\begin{tabular}{llrrrrrrrrr}
\toprule
Domain & Definition & $|A|$ & $|B|$ & $n^\ast$ & $A_{\mathrm{held}}$ & $B_{\mathrm{te}}$ & Lots & Shared (\%) & $s$ (RMSE) & $s$ (MAE) \\
\midrule
""" + body + r"""
\bottomrule
\end{tabular}
\end{table*}
""")
    sd = pd.read_csv(R / "shift_diag/main/summary/candidates.csv").set_index("candidate")
    shift_stats = pd.read_csv(R / "shift_statistics/main/shift_stats.csv").set_index("candidate")
    pl = sd[sd.index.str.startswith("placebo")]
    assert len(pl) == 10
    lines = []
    for n in sorted(names, key=lambda c: ORDER.index(short(c))):
        r = sd.loc[n]
        lines.append(f"{tex(short(n))} & {r.feature_ot_excess:.2f} $\\pm$ {r.feature_ot_excess_sd:.2f} & {10 * r.feature_ot_excess_placebo_pos:.0f}/10 & "
                     f"{r.disde_yx_abs_pct:.1f} $\\pm$ {r.disde_yx_abs_pct_sd:.1f} & {10 * r.disde_yx_abs_pct_placebo_pos:.0f}/10 & "
                     f"{r.prop_auc:.2f} & {shift_stats.loc[n, 'dmean_y']:+.4f} \\\\")
    rng = (f"feature OT excess {pl.feature_ot_excess.min():.2f} to {pl.feature_ot_excess.max():.2f}, "
           f"DISDE $Y\\mid X$ term {pl.disde_yx_abs_pct.min():.1f}\\% to {pl.disde_yx_abs_pct.max():.1f}\\%")
    (OUT / "tab_shift.tex").write_text(r"""% generated by tools/tables_dataset.py
\begin{table}[!t]
\footnotesize
\centering
\caption{Shift diagnostics of the challenge domains, computed on $A_{\mathrm{dev}}$ against $B_{\mathrm{tr}} \cup B_{\mathrm{scr}}$ (test sets not used). Feature OT: feature-space Sinkhorn divergence minus a lot-split reference within $A_{\mathrm{dev}}$, mean $\pm$ SD over ten subsamples. DISDE: $Y \mid X$ term on the shared feature distribution as a percentage of the source absolute loss, mean $\pm$ SD over ten lot-level source splits. $k$: number of the ten randomized lot-split controls with a smaller value. AUC: lot-grouped domain classifier. $\Delta\bar{y}$: target minus source mean defect rate. Control ranges: """ + rng + r""".}
\label{tab:shift}
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lrrrrrr}
\toprule
Domain & Feature OT & $k$ & DISDE (\%) & $k$ & AUC & $\Delta\bar{y}$ \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
    print((OUT / "tab_domains.tex").read_text()[-1400:])
    print((OUT / "tab_shift.tex").read_text()[-900:])


if __name__ == "__main__":
    if len(sys.argv) > 1:   # the generator takes no arguments and rewrites all of its outputs
        raise SystemExit(__doc__)
    main()
