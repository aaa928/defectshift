"""Appendix tables of the direction checks (output of paper/analysis/direction_checks.py): tab_block (the target-reference gap interval and the
direction classes under independent and block resampling of the target test lots) and tab_scaleterm (the share of fits in which the outcome-scale term
is the larger term of the ID-OOD gap).
Input (results/): analysis/direction_checks/{block_directions.csv, scale_dominance_domain.csv, scale_dominance_summary.csv}
Output: tables/tab_block.tex, tables/tab_scaleterm.tex"""
import sys
from pathlib import Path

import pandas as pd

from defectshift import config  # noqa: E402

R = Path(config.RESULTS_DIR) / "analysis" / "direction_checks"
HERE = Path(__file__).resolve().parent.parent
ORDER = ["cat_005", "cat_019", "cat_039", "cat_045", "cat_050", "x_time", "y_time"]
MET = (("rmse", "RMSE"), ("mae", "MAE"))
CODE = {"agree": "A", "disagree": "D", "unresolved": "U"}


def tex(s):
    return s.replace("_", r"\_")


def tab_block():
    b = pd.read_csv(R / "block_directions.csv")
    assert set(b.n_models) == {22}, "the tables of the paper use all 22 models"
    blk = b[b.scheme != "iid"]
    n_changed, n_all = int((blk.io_changed_vs_iid | blk.sn_changed_vs_iid).sum()), len(blk)
    n_schemes = blk.groupby(["dom", "metric"]).size().unique()
    assert len(n_schemes) == 1
    lines = []
    for d in ORDER:
        for k, (m, name) in enumerate(MET):
            i = b[(b.dom == d) & (b.metric == m) & (b.scheme == "iid")].iloc[0]
            x = blk[(blk.dom == d) & (blk.metric == m)]
            ch = int((x.io_changed_vs_iid | x.sn_changed_vs_iid).sum())
            lines.append(f"{tex(d) if k == 0 else ''} & {name} & [{i.tr_lo:.1f}, {i.tr_hi:.1f}] & [{x.tr_lo.min():.1f}, {x.tr_hi.max():.1f}] & "
                         f"{CODE[i.class_io]}/{CODE[i.class_sn]} & {ch} \\\\")
    changed = blk[blk.io_changed_vs_iid | blk.sn_changed_vs_iid]
    (HERE / "tables/tab_block.tex").write_text(r"""% generated by tools/tables_direction.py
\begin{table}[!t]
\footnotesize
\centering
\caption{Direction checks under block resampling of the target test lots (lot-disjoint target rows, all 22 models). Interval: 95\% interval of the target-reference gap (\%) from 2,000 resamples, for independently resampled lots and as the range over the """ + f"{int(n_schemes[0])}" + r""" block schemes (circular and moving blocks of 2, 5, and 10 lots in the production order of the lots; lowest lower and highest upper bound). Class: direction class (A agree, D disagree, U unresolved) of the ID--OOD gap with the target-reference gap before and after outcome-scale normalization under independent resampling (Table~\ref{tab:rq1}). Changed: number of block schemes in which either class differs. The class changes in """ + f"{n_changed} of {n_all}" + r""" domain--measure--scheme cases.}
\label{tab:block}
\setlength{\tabcolsep}{3pt}
\begin{tabular}{llcccc}
\toprule
 & & \multicolumn{2}{c}{Interval} & & \\
\cmidrule(lr){3-4}
Domain & Measure & Independent & Block schemes & Class & Changed \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
    return changed[["dom", "metric", "scheme", "block", "tr_lo", "tr_hi"]]


def tab_scaleterm():
    d = pd.read_csv(R / "scale_dominance_domain.csv")
    s = pd.read_csv(R / "scale_dominance_summary.csv").set_index("metric")
    n_fits = int(d.n_fits.unique()[0])
    assert n_fits == 22 * 5, "the caption states 22 models times five repetitions"
    lines = []
    for dom in ORDER:
        cells = []
        for m, _ in MET:
            r = d[(d.dom == dom) & (d.metric == m)].iloc[0]
            cells.append(f"{100 * r.share_fits_scale_term_larger:.0f} & {r.D_fit_median:+.2f}")
        lines.append(f"{tex(dom)} & " + " & ".join(cells) + r" \\")
    (HERE / "tables/tab_scaleterm.tex").write_text(r"""% generated by tools/tables_direction.py
\begin{table}[!t]
\footnotesize
\centering
\caption{The outcome-scale term of the ID--OOD gap (lot-disjoint target rows). Share: percentage of the """ + f"{n_fits}" + r""" fits (22 models times five repetitions) in which the outcome-scale term $\log s$ is larger in magnitude than the sum of the other two terms, $\log q + \log(1+\gTR)$, i.e. $\Delta = |\log s| - |\log(1+\gIO) - \log s| > 0$; $\mathrm{med}(\Delta)$: median of $\Delta$ over the fits. The term is larger in a domain when $\mathrm{med}(\Delta) > 0$: in """ + f"{int(s.loc['rmse', 'n_larger_fit_median'])} of {int(s.loc['rmse', 'n_domains'])} domains for RMSE and {int(s.loc['mae', 'n_larger_fit_median'])} of {int(s.loc['mae', 'n_domains'])} for MAE" + r""".}
\label{tab:scaleterm}
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lrrrr}
\toprule
 & \multicolumn{2}{c}{RMSE} & \multicolumn{2}{c}{MAE} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}
Domain & Share (\%) & $\mathrm{med}(\Delta)$ & Share (\%) & $\mathrm{med}(\Delta)$ \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
""")


def main():
    ch = tab_block()
    tab_scaleterm()
    print("class changes under block resampling:")
    print(ch.round(2).to_string(index=False))


if __name__ == "__main__":
    if len(sys.argv) > 1:   # the generator takes no arguments and rewrites all of its outputs
        raise SystemExit(__doc__)
    main()
